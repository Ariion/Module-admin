export function createTranslator(lang = 'fr') {
  const dict = DICTIONARIES[lang] || DICTIONARIES.fr;
  return (key, ...args) => {
    const value = dict[key] ?? DICTIONARIES.fr[key] ?? key;
    return typeof value === 'function' ? value(...args) : value;
  };
}
